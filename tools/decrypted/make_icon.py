"""Build the game's icon files from platform/icon/icon.png (64x64 pixel art).

Writes platform/icon/ctr.ico (the exe's icon on Windows, which SDL also gives
the window and taskbar), platform/icon/native_icon_pixels.h (the window icon
elsewhere) and platform/icon/icon-256.png (README.md). Large sizes are exact pixel multiples of the source; small ones
are box-filtered from it.

    python tools/decrypted/make_icon.py
"""
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
ICON_DIR = ROOT / "platform" / "icon"


def main():
    src = Image.open(ICON_DIR / "icon.png").convert("RGBA")
    assert src.size == (64, 64), src.size

    frames = []
    for size in (256, 128, 64, 48, 32, 24, 16):
        method = Image.Resampling.NEAREST if size % 64 == 0 else Image.Resampling.BOX
        frames.append(src.resize((size, size), method))
    frames[0].save(ICON_DIR / "ctr.ico", format="ICO", sizes=[f.size for f in frames], append_images=frames[1:])
    # Shown at its own size in README.md, so the browser doesn't blur the pixels.
    frames[0].save(ICON_DIR / "icon-256.png")

    # Indexed: a palette and one byte per pixel keeps the header small.
    pixels = [src.getpixel((x, y)) for y in range(64) for x in range(64)]
    palette = sorted(set(pixels))
    index = {p: i for i, p in enumerate(palette)}
    lines = [
        "// Generated by tools/decrypted/make_icon.py from platform/icon/icon.png. Do not edit.",
        "#pragma once",
        "",
        "#define NATIVE_ICON_SIZE 64",
        "",
        "// RGBA",
        "static const unsigned char kNativeIconPalette[][4] = {",
    ]
    lines += ["\t{%d, %d, %d, %d}," % p for p in palette]
    lines += ["};", "", "static const unsigned char kNativeIconPixels[NATIVE_ICON_SIZE * NATIVE_ICON_SIZE] = {"]
    for y in range(64):
        row = pixels[y * 64:(y + 1) * 64]
        lines.append("\t" + ",".join(str(index[p]) for p in row) + ",")
    lines += ["};", ""]
    (ICON_DIR / "native_icon_pixels.h").write_text("\n".join(lines), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
